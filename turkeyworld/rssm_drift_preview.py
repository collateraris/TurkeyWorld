"""JSON geometry from an existing preview trajectory; no simulator or model calls."""
from __future__ import annotations

import math

import numpy as np


KIND = 'rssm_preview_map_drift_v1'
MAP_SIZE = 16


def _array(value, name):
    # A collected GPU trajectory is copied once for disclosure, never fed back.
    if hasattr(value, 'detach'):
        value = value.detach().cpu().double().numpy()
    try:
        result = np.asarray(value, dtype=np.float64)
    except (TypeError, ValueError) as error:
        raise ValueError(name+' must be numeric') from error
    if not np.isfinite(result).all():
        raise ValueError(name+' must be finite')
    return result


def _angle(x, y):
    return None if math.hypot(float(x), float(y)) <= 1e-12 else float(math.atan2(y, x))


def _actors(states):
    npc_alive = (states[:, 13] >= .5) & (states[:, 12] > 0)
    player_heading = [_angle(row[3], row[2]) for row in states]
    velocity = states[:, 10:12]*2
    respawn = np.zeros(len(states), dtype=bool)
    respawn[1:] = ~npc_alive[:-1] & npc_alive[1:]
    continuing = np.zeros(len(states), dtype=bool)
    continuing[1:] = npc_alive[:-1] & npc_alive[1:]
    life = 0 if bool(npc_alive[0]) else -1
    lives = []
    for index in range(len(states)):
        life += int(respawn[index])
        lives.append(life)
    motion = np.zeros((len(states), 2), dtype=np.float64)
    motion[1:] = np.diff(states[:, 8:10], axis=0)*MAP_SIZE
    return {
        'player_xy': (states[:, :2]*MAP_SIZE).tolist(),
        'player_heading': player_heading,
        'player_heading_valid': [value is not None for value in player_heading],
        'player_alive': (states[:, 4] > 0).tolist(),
        # Keep corpse coordinates disclosed; npc_alive controls drawing/error support.
        'npc_xy': (states[:, 8:10]*MAP_SIZE).tolist(),
        'npc_alive': npc_alive.tolist(),
        'npc_velocity_xy': velocity.tolist(),
        'npc_direction': [_angle(*row) if bool(alive) else None
                          for row, alive in zip(velocity, npc_alive)],
        'npc_motion_direction': [_angle(*row) if bool(alive) else None
                                 for row, alive in zip(motion, continuing)],
        'npc_respawn': respawn.tolist(),
        'npc_life_index': lives,
    }


def _supported(values):
    valid = [value for value in values if value is not None]
    return {'mean': float(sum(valid)/len(valid)) if valid else None,
            'max': float(max(valid)) if valid else None, 'count': len(valid)}


def build_drift_preview(batch, spec, own_states, *, step):
    """Describe the SAME H transitions already generated by the image preview.

    ``own_states`` is [H+1,20], including the unchanged initial state at
    ``context-1``. Source is sliced at that same frame from ``batch['states']``.
    NPC heading is not stored in the state: ``npc_direction`` means its stored
    velocity direction; ``npc_motion_direction`` means adjacent XY displacement.
    Both are null for zero motion, and no displacement arrow bridges a spawn.
    """
    horizon, context = spec.get('horizon'), spec.get('context')
    offsets = spec.get('display_offsets')
    if (type(step) is not int or step < 0 or type(horizon) is not int
            or not 4 <= horizon <= 450 or type(context) is not int or context not in (1, 2)
            or not isinstance(offsets, (list, tuple)) or len(offsets) != 4
            or any(type(value) is not int for value in offsets)
            or list(offsets) != sorted(set(offsets)) or offsets[0] != 1 or offsets[-1] != horizon):
        raise ValueError('Drift preview requires the actual step/context/H and four ordered display offsets')
    source_batch = _array(batch['states'], 'Source states')
    own = _array(own_states, 'Own states')
    grids = _array(batch['map'], 'Map')
    if (source_batch.ndim != 3 or source_batch.shape[0] != 1 or source_batch.shape[2] != 20
            or source_batch.shape[1] < context+horizon or own.shape != (horizon+1, 20)
            or grids.shape != (1, MAP_SIZE, MAP_SIZE)
            or np.any(grids < 0) or np.any(grids != np.floor(grids))):
        raise ValueError('Drift preview needs one complete [H+1,20] own trajectory and its16x16 map')
    source = source_batch[0, context-1:context+horizon]
    if not np.array_equal(own[0], source[0]):
        raise ValueError('Own and Source drift preview initial states must match at context-1')
    reference, prediction = _actors(source), _actors(own)
    player_delta = (own[:, :2]-source[:, :2])*MAP_SIZE
    npc_delta = (own[:, 8:10]-source[:, 8:10])*MAP_SIZE
    common = np.asarray(reference['npc_alive']) & np.asarray(prediction['npc_alive'])
    same_life = (np.asarray(reference['npc_life_index']) == np.asarray(prediction['npc_life_index']))
    continuing = np.zeros(horizon+1, dtype=bool)
    continuing[1:] = (np.asarray(reference['npc_alive'])[:-1]
                      & np.asarray(reference['npc_alive'])[1:])
    pnorm, nnorm = np.linalg.norm(player_delta, axis=1), np.linalg.norm(npc_delta, axis=1)
    heading_error = [None if a is None or b is None else
                     float(abs(math.degrees(math.atan2(math.sin(a-b), math.cos(a-b)))))
                     for a, b in zip(prediction['player_heading'], reference['player_heading'])]
    errors = {
        'player_xy_error_tiles': pnorm.tolist(),
        'player_dx_tiles': player_delta[:, 0].tolist(),
        'player_dy_tiles': player_delta[:, 1].tolist(),
        'player_heading_error_degrees': heading_error,
        'npc_xy_error_tiles': [float(value) if bool(valid) else None for value, valid in zip(nnorm, common)],
        'npc_dx_tiles': [float(value) if bool(valid) else None for value, valid in zip(npc_delta[:, 0], common)],
        'npc_dy_tiles': [float(value) if bool(valid) else None for value, valid in zip(npc_delta[:, 1], common)],
        'npc_alive_mismatch': (np.asarray(reference['npc_alive']) != np.asarray(prediction['npc_alive'])).tolist(),
        'npc_source_continuing': continuing.tolist(),
        'npc_continuing_xy_error_tiles': [float(value) if bool(valid) else None
                                         for value, valid in zip(nnorm, common & continuing)],
        'npc_same_life_xy_error_tiles': [float(value) if bool(valid) else None
                                        for value, valid in zip(nnorm, common & same_life)],
        'npc_life_mismatch': [bool(valid and a != b) for valid, a, b in
                              zip(common, reference['npc_life_index'], prediction['npc_life_index'])],
    }
    world_map = grids[0].astype(np.int64)
    frames = []
    for offset in offsets:
        frames.append({'offset': offset, 'time_seconds': float(offset/30),
            'reference': {name: values[offset] for name, values in reference.items()},
            'prediction': {name: values[offset] for name, values in prediction.items()},
            'errors': {name: values[offset] for name, values in errors.items()}})
    return {
        'kind': KIND, 'step': step, 'context': context, 'horizon': horizon,
        'generated_rollout_transitions': horizon, 'display_offsets': list(offsets),
        'offsets': list(range(horizon+1)), 'time_seconds': [float(i/30) for i in range(horizon+1)],
        'source_frame_indices': list(range(context-1, context+horizon)),
        'map_size': MAP_SIZE, 'world_map': world_map.tolist(),
        'wall_cells': [[int(x), int(y), int(world_map[y, x])] for y, x in np.argwhere(world_map != 0)],
        'coordinates': 'map_tiles', 'map_axes': 'world_map[y][x]; +x right, +y down',
        'direction_units': 'radians; 0=+x, pi/2=+y',
        'npc_direction_definition': 'Stored velocity direction (state vx/2,vy/2 multiplied by2); not an NPC viewing angle',
        'npc_motion_direction_definition': 'Adjacent own XY displacement; null on zero motion, death or birth',
        'reference': reference, 'prediction': prediction, 'errors': errors, 'display_frames': frames,
        'summary': {
            # Only future transitions enter aggregates; initial zero error does not dilute them.
            'player_xy_error_tiles': _supported(errors['player_xy_error_tiles'][1:]),
            'npc_common_alive_xy_error_tiles': _supported(errors['npc_xy_error_tiles'][1:]),
            'npc_continuing_xy_error_tiles': _supported(errors['npc_continuing_xy_error_tiles'][1:]),
            'npc_same_life_xy_error_tiles': _supported(errors['npc_same_life_xy_error_tiles'][1:]),
            'npc_alive_mismatch_frames': int(sum(errors['npc_alive_mismatch'][1:])),
            'reference_spawn_offsets': [i for i, value in enumerate(reference['npc_respawn']) if value],
            'prediction_spawn_offsets': [i for i, value in enumerate(prediction['npc_respawn']) if value],
        },
        'npc_xy_error_mask': 'Both alive at this offset; dead/missing is null, not zero error; births may be measured',
        'npc_continuing_xy_error_mask': 'Source alive before and after, prediction alive now; exact Source births excluded',
        'npc_same_life_xy_error_mask': 'Both alive and equal within-preview life index; excludes positions of different predicted/Source lives',
        'initial_state_equal': True, 'generated_finite': True, 'simulation_hz': 30, 'transition_hz': 30,
        'source_states_are_labels_only': True, 'source_future_feedback': False,
        'additional_model_transitions': 0, 'additional_engine_queries': 0,
    }
